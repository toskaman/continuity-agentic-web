/**
 * CONTINUITY ecosystem design system builder.
 *
 * Composes each app's styles.css from the shared design system and copies the
 * shared assets every independent origin needs (no cross-origin CSS/JS/fonts):
 *
 *   design-system/base.css            tokens, components, runtime skin, motion
 *   design-system/peer.css            layout shared by the four peer sites
 *   design-system/themes/<app>.css    per-site identity
 *   design-system/peer-ui-kit.js      -> apps/<app>/ui-kit.js
 *   design-system/fonts/*             -> apps/<app>/assets/fonts/
 *
 * Usage: node scripts/write_peer_styles.mjs [--check]
 */
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const DS = path.join(ROOT, "design-system");
const CHECK = process.argv.includes("--check");

const APPS = [
  { dir: "continuity-web", peer: false },
  { dir: "demo-moveco", peer: true },
  { dir: "demo-permitflow", peer: true },
  { dir: "demo-homeconnect", peer: true },
  { dir: "demo-powerflow", peer: true },
];

const read = (p) => readFile(path.join(DS, p), "utf8");
const base = await read("base.css");
const peer = await read("peer.css");
const kit = await read("peer-ui-kit.js");

let drift = 0;
for (const app of APPS) {
  const appDir = path.join(ROOT, "apps", app.dir);
  const theme = await read(path.join("themes", `${app.dir}.css`));
  const css = [
    `/* GENERATED by scripts/write_peer_styles.mjs — do not edit here.\n   Source: design-system/base.css${app.peer ? " + peer.css" : ""} + themes/${app.dir}.css */\n`,
    base,
    app.peer ? peer : "",
    theme,
  ].join("\n");

  if (CHECK) {
    const current = await readFile(path.join(appDir, "styles.css"), "utf8").catch(() => "");
    if (current !== css) {
      console.error(`✕ ${app.dir}/styles.css is out of date`);
      drift += 1;
    }
    continue;
  }

  await writeFile(path.join(appDir, "styles.css"), css, "utf8");
  await writeFile(path.join(appDir, "ui-kit.js"), kit, "utf8");
  await mkdir(path.join(appDir, "assets", "fonts"), { recursive: true });
  for (const f of ["inter-var-latin.woff2", "OFL.txt"]) {
    await copyFile(path.join(DS, "fonts", f), path.join(appDir, "assets", "fonts", f));
  }
  console.log(`✓ ${app.dir}: styles.css, ui-kit.js, assets/fonts`);
}

if (CHECK) {
  if (drift) process.exit(1);
  console.log("✓ All 5 stylesheets match the design system.");
}
